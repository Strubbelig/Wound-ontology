"""The extraction schema is a snapshot of WONT + MILD, and it checks its own age.

Until 2026-09-12 `config/extraction_schema.yaml` was regenerated by hand, when
someone remembered. Extraction prompted with whatever snapshot was on disk and
said nothing about how old it was. This pins the check that now runs at the top
of `run_extract_to_store`: stale is detected, a no-op rebuild does not churn the
tree, a real change is written and STOPS the process that imported the old one.
"""
from __future__ import annotations

import os
import time
from pathlib import Path

import pytest

from wound_ontology.llm import schema_builder as sb


# ── harness ──────────────────────────────────────────────────────────────────

def _age(path: Path, seconds_ago: float) -> None:
    t = time.time() - seconds_ago
    os.utime(path, (t, t))


@pytest.fixture
def world(tmp_path, monkeypatch):
    """Two sources, a modules dir with one module, two outputs; all current."""
    wont = tmp_path / "wont.owl"; wont.write_text("w")
    mild = tmp_path / "mild.ttl"; mild.write_text("m")
    mods = tmp_path / "modules"; mods.mkdir()
    obi = mods / "obi_module.owl"; obi.write_text("o")
    yaml = tmp_path / "extraction_schema.yaml"
    py = tmp_path / "extraction_models.py"
    yaml.write_text("# Generated:        2026-09-08\nid: x\n")
    py.write_text('"""GENERATED\n\nGenerated:        2026-09-08\n\nbody"""\nX = 1\n')
    for p in (wont, mild, obi):
        _age(p, 100)
    monkeypatch.setattr(sb, "WONT_TTL", wont)
    monkeypatch.setattr(sb, "MILD_TTL", mild)
    monkeypatch.setattr(sb, "MODULES", mods)
    monkeypatch.setattr(sb, "OUT_YAML", yaml)
    monkeypatch.setattr(sb, "OUT_PY", py)
    monkeypatch.setattr(sb, "PROJ", tmp_path)
    return dict(wont=wont, mild=mild, obi=obi, yaml=yaml, py=py)


def _rebuild_returns(monkeypatch, yaml_text, py_text):
    calls = []
    def fake_build(onto=None):
        calls.append(1)
        return yaml_text, py_text
    monkeypatch.setattr(sb, "build", fake_build)
    return calls


# ── staleness ────────────────────────────────────────────────────────────────

def test_a_current_schema_is_not_stale(world):
    assert sb.stale() == []


@pytest.mark.parametrize("which", ["wont", "mild", "obi"])
def test_any_newer_source_makes_it_stale_and_is_named(world, which):
    """WONT, MILD and the import modules all feed the category resolution."""
    _age(world[which], 0)  # now: newer than both outputs
    reasons = sb.stale()
    assert reasons, "a newer source went unnoticed"
    assert all(world[which].name in r for r in reasons)
    assert len(reasons) == 2, "one reason per output that fell behind"


def test_a_missing_output_is_stale(world):
    world["py"].unlink()
    assert any("extraction_models.py does not exist" in r for r in sb.stale())


def test_a_missing_source_is_reported_not_built_around(world):
    """The schema IS the sources. Without one there is nothing honest to build."""
    world["mild"].unlink()
    reasons = sb.stale()
    assert reasons and all(r.startswith("source missing") for r in reasons)


# ── ensure_current ───────────────────────────────────────────────────────────

def test_current_means_nothing_is_touched(world, monkeypatch):
    calls = _rebuild_returns(monkeypatch, "unused", "unused")
    before = (world["yaml"].stat().st_mtime_ns, world["py"].stat().st_mtime_ns)
    assert sb.ensure_current(quiet=True) == "current"
    assert calls == [], "a current schema must not cost a 33 s rebuild"
    assert (world["yaml"].stat().st_mtime_ns, world["py"].stat().st_mtime_ns) == before


def test_a_rebuild_that_only_moves_the_date_touches_and_does_not_rewrite(world, monkeypatch):
    """Measured 2026-09-12: a fresh build against the 4 Sep WONT differed from
    the 8 Sep file in exactly one line, the date. Rewriting would dirty the tree
    on every WONT save that changed nothing the schema carries."""
    _age(world["wont"], 0)
    old_yaml, old_py = world["yaml"].read_text(), world["py"].read_text()
    calls = _rebuild_returns(monkeypatch,
                             old_yaml.replace("2026-09-08", "2026-09-12"),
                             old_py.replace("2026-09-08", "2026-09-12"))
    assert sb.ensure_current(quiet=True) == "touched"
    assert calls == [1]
    assert world["yaml"].read_text() == old_yaml, "the date line was rewritten"
    assert world["py"].read_text() == old_py
    assert sb.stale() == [], "touching must make the next call cheap"


def test_a_rebuild_that_changes_content_is_written(world, monkeypatch):
    _age(world["mild"], 0)
    _rebuild_returns(monkeypatch,
                     "# Generated:        2026-09-12\nid: x\nnew_class: Open wound\n",
                     '"""GENERATED\n\nGenerated:        2026-09-12\n\nbody"""\nX = 2\n')
    assert sb.ensure_current(quiet=True) == "rewritten"
    assert "Open wound" in world["yaml"].read_text()
    assert "X = 2" in world["py"].read_text()
    assert sb.stale() == []


def test_the_stamp_is_the_only_line_ignored():
    """Both emitters stamp differently: `# Generated:` in YAML, bare in the
    module docstring. Anything else that differs must count."""
    assert sb._without_stamp("# Generated:        2026-09-08\nid: x\n") \
        == sb._without_stamp("# Generated:        2026-09-12\nid: x\n")
    assert sb._without_stamp("Generated:        2026-09-08\n\nbody") \
        == sb._without_stamp("Generated:        2026-09-12\n\nbody")
    assert sb._without_stamp("id: x\n") != sb._without_stamp("id: y\n")
    assert sb._without_stamp("# Generated by hand\n") != sb._without_stamp("# Generated by foot\n")


# ── the call site ────────────────────────────────────────────────────────────

def _bare_orchestrator():
    """run_extract_to_store must decide about the schema before it touches
    self.store, so an instance with nothing else on it is enough."""
    from wound_ontology.orchestrator import Orchestrator
    o = object.__new__(Orchestrator)
    o.pubcon = type("P", (), {"database": None})()
    o.llm = None
    o.allowed_predicates = []
    return o


class _Store:
    def __init__(self):
        self.called = False

    async def add_llm_extracts(self, *a, **kw):
        self.called = True


def test_extraction_refuses_to_run_on_a_schema_it_did_not_import(monkeypatch):
    monkeypatch.setattr(sb, "ensure_current", lambda quiet=False: "rewritten")
    o = _bare_orchestrator()
    o.store = _Store()
    with pytest.raises(RuntimeError, match="Restart the Python process"):
        o.run_extract_to_store(use_bfo_attributes=False)
    assert o.store.called is False, "extraction ran against the old schema"


@pytest.mark.parametrize("outcome", ["current", "touched"])
def test_extraction_proceeds_when_the_imported_schema_is_the_one_on_disk(monkeypatch, outcome):
    import asyncio
    monkeypatch.setattr(sb, "ensure_current", lambda quiet=False: outcome)
    o = _bare_orchestrator()
    o.store = _Store()
    o._run_sync = lambda coro: asyncio.run(coro)
    o.run_extract_to_store(use_bfo_attributes=False)
    assert o.store.called is True


def test_the_check_runs_before_anything_else_in_extraction():
    """It has to come first: after the first LLM call the damage is done."""
    import ast, inspect
    from wound_ontology.orchestrator import Orchestrator
    src = inspect.getsource(Orchestrator.run_extract_to_store)
    tree = ast.parse("class _:\n" + "\n".join("    " + l for l in src.splitlines()))
    fn = tree.body[0].body[0]
    body = [n for n in fn.body
            if not (isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant))]
    first_call = next(n for n in body if isinstance(n, ast.Assign))
    assert isinstance(first_call.value, ast.Call)
    assert first_call.value.func.attr == "ensure_current"
